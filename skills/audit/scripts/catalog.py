#!/usr/bin/env python3
"""The documentation catalog: one generated entry for every part of a repo, so none can go undocumented.

Usage:
    catalog.py [repo] --write   # writes docs/CATALOG.md from the code
    catalog.py [repo] --check   # exit 1 when the catalog is stale or a part has no one-line job
Every skill (frontmatter description), script (first docstring or comment line, plus its Usage line) and
config file (its _comment or description) gets one row. A part with no job line is a documentation gap to
fix in the part itself, since the catalog only repeats what the part says about itself.
Tests: python3 -m unittest test_catalog
"""

import json
import re
import sys
from pathlib import Path

import _fleet
from _fleet import is_test, scan_root, tracked

OUT = "docs/CATALOG.md"
SCRIPT = {".py", ".sh", ".js", ".mjs", ".cjs"}
CONFIG = {".json", ".toml", ".yml", ".yaml"}
LOCKS = ("package-lock.json", "yarn.lock", "pnpm-lock.yaml")
NONE = "(no description)"


def first_sentence(text, limit=200):
    text = " ".join(text.split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text)[:limit]


def script_info(text, suffix):
    """(job, usage) from a module docstring or the leading comment block."""
    body = ""
    if suffix == ".py":
        m = re.search(r'\A(?:#!.*\n)?(?:#.*\n)*\s*(?:"""|\'\'\')((?s:.*?))(?:"""|\'\'\')', text)
        body = m.group(1) if m else ""
    else:
        lines = []
        for line in text.splitlines():
            s = line.strip()
            if s.startswith("#!") or not s:
                if lines:
                    break
                continue
            if s.startswith(("#", "//", "/*", "*")):
                lines.append(re.sub(r"^(#|//|/\*+|\*+/?)\s?", "", s))
            else:
                break
        body = "\n".join(lines)
    body = body.strip()
    job = ""
    for para in re.split(r"\n\s*\n", body):
        flat = " ".join(para.split())
        if flat and not flat.lower().startswith(("usage", "tests:")):
            job = first_sentence(re.sub(r"^\S*[/\w.-]+\.(py|sh|js)\s+[—-]\s+", "", flat))
            break
    usage = re.search(r"^\s*Usage:\s*(?:\n\s*)?(\S.*)$", body, re.M)
    return job, (usage.group(1).strip() if usage else "")


def skill_info(text):
    desc = _fleet.description_text(text)
    return first_sentence(re.sub(r"^[>|-]\s*", "", desc.strip('"\''))) if desc else ""


def config_info(text, suffix):
    if suffix == ".json":
        try:
            data = json.loads(text)
        except ValueError:
            return ""
        if isinstance(data, dict):
            for key in ("_comment", "_doc", "description", "_purpose"):
                if isinstance(data.get(key), str):
                    return first_sentence(data[key])
    first = next((l for l in text.splitlines() if l.strip().startswith("#")), "")
    return first_sentence(first.lstrip("# ")) if first else ""


def entries(repo):
    rows = {"Skills": [], "Scripts": [], "Config": []}
    for rel in sorted(tracked(repo)):
        p = Path(rel)
        if "fixtures" in p.parts:
            continue
        suffix = p.suffix or shebang_suffix(Path(repo) / rel)
        text = (Path(repo) / rel).read_text(encoding="utf-8", errors="ignore") if suffix in SCRIPT | CONFIG | {".md"} else ""
        if p.name == "SKILL.md":
            rows["Skills"].append((f"`{p.parent.name}`", skill_info(text) or NONE, ""))
        elif suffix in SCRIPT and not is_test(rel) and p.name != "__init__.py" and ({"scripts", "hooks", ".githooks"} & set(p.parts)) and rel != OUT:
            job, usage = script_info(text, suffix)
            rows["Scripts"].append((f"`{rel}`", job or NONE, f"`{usage}`" if usage else ""))
        elif p.suffix in CONFIG and not p.name.endswith(LOCKS) and not is_test(rel) and not p.name.startswith(".") and rel != OUT:
            rows["Config"].append((f"`{rel}`", config_info(text, p.suffix) or NONE, ""))
    return rows


def shebang_suffix(path):
    """The suffix an extensionless script would have, from its #! line, so a launcher such as scripts/olivercode is listed."""
    try:
        with open(path, "rb") as f:
            first = f.readline(200).decode("utf-8", "ignore")
    except OSError:
        return ""
    if not first.startswith("#!"):
        return ""
    if "python" in first:
        return ".py"
    if "node" in first:
        return ".js"
    return ".sh" if ("bash" in first or first.rstrip().endswith("/sh")) else ""


def render(rows):
    out = ["# Catalog", "", "Generated by the audit skill's `catalog.py --write`. Edit a part's own description, never this file.", ""]
    for name, items in rows.items():
        if not items:
            continue
        out += [f"## {name}", "", "| Part | Job | Start |", "|---|---|---|"]
        out += [f"| {a} | {b.replace('|', '/')} | {c.replace('|', '/')} |" for a, b, c in items] + [""]
    return "\n".join(out)


def check(repo):
    problems = []
    rows = entries(repo)
    for name, items in rows.items():
        problems += [f"{name[:-1].lower()} {a.strip('`')} has no description" for a, b, _ in items if b == NONE]
    target = Path(repo) / OUT
    if not target.exists() or target.read_text(encoding="utf-8") != render(rows) + "\n":
        problems.append(f"{OUT} is missing or stale. Fix: python3 skills/audit/scripts/catalog.py --write")
    return problems


def main(argv):
    flags = {a for a in argv[1:] if a.startswith("--")}
    repo = scan_root(argv[1:], Path("."))
    if "--write" in flags:
        (Path(repo) / OUT).parent.mkdir(exist_ok=True)
        (Path(repo) / OUT).write_text(render(entries(repo)) + "\n", encoding="utf-8")
        print(f"wrote {OUT}")
        return 0
    problems = check(repo)
    for p in problems:
        print("CATALOG: " + p)
    if not problems:
        print("catalog: complete.")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
